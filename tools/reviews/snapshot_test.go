// reReviewTools fakes a pull request that moved from oldHeadSHA to headSHA with the previous record's body.
func reReviewTools(t *testing.T, recordBody string, rangeDiff string, patches map[string]string) (tools, *fakeRunner) {
	t.Helper()
	pr := pullHandler(t, samplePR, headSHA)
	gh := func(args []string) ([]byte, error) {
		if args[0] == "api" {
			if args[1] != "repos/shgew/togi/issues/comments/4242" {
				return nil, fmt.Errorf("unexpected api %v", args)
			}
			b, _ := json.Marshal(map[string]any{"body": recordBody, "user": map[string]string{"login": "robotogi[bot]"}})
			return b, nil
		}
		return pr(args)
	}
	git := func(args []string) ([]byte, error) {
		switch args[0] {
		case "fetch":
			return nil, nil
		case "range-diff":
			return []byte(rangeDiff), nil
		case "diff":
			key := args[len(args)-2] + " " + args[len(args)-1]
			if p, ok := patches[key]; ok {
				return []byte(p), nil
			}
		}
		return nil, fmt.Errorf("unexpected git %v", args)
	}
	tl, _, c, _, _ := testTools(t, gh, git)
	return tl, c
}

func previousBody(version int, base string) string {
	b := fmt.Sprintf(`{"version":%d,"head_sha":%q,"findings":[]`, version, oldHeadSHA)
	if base != "" {
		b += fmt.Sprintf(`,"base_sha":%q`, base)
	}
	return "## Review record\n\n<!-- togi-review " + b + "} -->\n"
}

func onePatch(file, context, added string) string {
	return "diff --git a/" + file + " b/" + file + "\n--- a/" + file + "\n+++ b/" + file + "\n@@ -5,3 +5,3 @@\n " + context + "\n-old\n+" + added + "\n tail\n"
}

func TestSnapshotReReviewClassifiesPatches(t *testing.T) {
	t.Parallel()
	rangeDiff := `1:  aaa1111 = 1:  bbb1111 stays the same
2:  aaa2222 ! 2:  bbb2222 only context moved
3:  aaa3333 ! 3:  bbb3333 edited added line
-:  ------- > 4:  bbb4444 new commit
4:  aaa5555 < -:  ------- dropped commit
`
	patches := map[string]string{
		"aaa2222^ aaa2222": onePatch("a.go", "before", "x"),
		"bbb2222^ bbb2222": onePatch("a.go", "other context", "x"),
		"aaa3333^ aaa3333": onePatch("b.go", "ctx", "v1"),
		"bbb3333^ bbb3333": onePatch("b.go", "ctx", "v2"),
		"bbb4444^ bbb4444": onePatch("c.go", "ctx", "fresh"),
		"aaa5555 aaa5555^": onePatch("d.go", "ctx", "gone"),
	}
	tl, git := reReviewTools(t, previousBody(3, oldBaseSHA), rangeDiff, patches)
	if err := runSnapshot(tl, []string{"--previous", previousURL, "700"}); err != nil {
		t.Fatal(err)
	}
	dir := snapshotDir(tl)
	var m manifest
	if err := json.Unmarshal([]byte(readFile(t, filepath.Join(dir, "manifest.json"))), &m); err != nil {
		t.Fatal(err)
	}
	want := []patchStatus{
		{Old: "aaa1111", New: "bbb1111", Subject: "stays the same", Status: "unchanged"},
		{Old: "aaa2222", New: "bbb2222", Subject: "only context moved", Status: "unchanged", ContextOnly: true},
		{Old: "aaa3333", New: "bbb3333", Subject: "edited added line", Status: "changed"},
		{New: "bbb4444", Subject: "new commit", Status: "added"},
		{Old: "aaa5555", Subject: "dropped commit", Status: "removed"},
	}
	if diff := cmp.Diff(want, m.Patches); diff != "" {
		t.Errorf("patches (-want +got):\n%s", diff)
	}
	if m.CarryForward {
		t.Error("a delta with changed, added and removed patches carried forward")
	}
	var paths []string
	for _, f := range m.Files {
		paths = append(paths, f.Path)
	}
	// The context-only and unchanged patches are not in the delta; the others are.
	if diff := cmp.Diff([]string{"b.go", "c.go", "d.go"}, paths); diff != "" {
		t.Errorf("delta files (-want +got):\n%s", diff)
	}
	delta := readFile(t, filepath.Join(dir, "delta.diff"))
	wantDelta := onePatch("b.go", "ctx", "v2") + onePatch("c.go", "ctx", "fresh") + onePatch("d.go", "ctx", "gone")
	if delta != wantDelta {
		t.Errorf("delta.diff = %q, want %q", delta, wantDelta)
	}
	if got := readFile(t, filepath.Join(dir, "pr.diff")); got != samplePR {
		t.Error("pr.diff must stay the whole frozen diff on a re-review")
	}
	if m.Small || m.PRFiles != 8 {
		t.Errorf("small = %t over %d files: the rule must measure the whole diff, not the delta", m.Small, m.PRFiles)
	}
	wantFetch := "git fetch --quiet origin " + oldBaseSHA + " " + oldHeadSHA + " " + baseSHA + " " + headSHA
	if got := git.joined()[0]; got != wantFetch {
		t.Errorf("first git call = %q, want %q", got, wantFetch)
	}
	if m.Previous == nil || m.Previous.URL != previousURL || m.Previous.HeadSHA != oldHeadSHA || m.Previous.BaseSHA != oldBaseSHA {
		t.Errorf("previous = %+v", m.Previous)
	}
}

