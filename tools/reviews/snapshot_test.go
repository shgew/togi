func TestParseDiff(t *testing.T) {
	t.Parallel()
	files, err := parseDiff(samplePR)
	if err != nil {
		t.Fatal(err)
	}
	type row struct {
		Path, Old, Status string
		Added, Removed    int
		Binary            bool
		Changed           []span
		Exclusion         string
	}
	var got []row
	for _, f := range files {
		got = append(got, row{f.Path, f.OldPath, f.Status, f.Added, f.Removed, f.Binary, f.Changed, excludedReason(f)})
	}
	want := []row{
		{Path: "cmd/togi/main.go", Status: "modified", Added: 3, Removed: 1, Changed: []span{{11, 12}, {42, 42}}},
		{Path: "go.sum", Status: "modified", Added: 1, Changed: []span{{2, 2}}, Exclusion: "generated"},
		{Path: "internal/old.go", Status: "deleted", Removed: 2},
		{Path: "docs/two.md", Old: "docs/one.md", Status: "renamed", Added: 1, Removed: 1, Changed: []span{{2, 2}}},
		{Path: "logo.png", Status: "added", Binary: true, Exclusion: "binary"},
		{Path: "pkg/testdata/in.txt", Status: "added", Added: 1, Changed: []span{{1, 1}}, Exclusion: "test data (`**/testdata/**`)"},
		{Path: "pkg/gen.go", Status: "added", Added: 2, Changed: []span{{1, 2}}, Exclusion: "generated"},
		{Path: "pkg/empty", Status: "added"},
	}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("files (-want +got):\n%s", diff)
	}
	var joined strings.Builder
	for _, f := range files {
		joined.WriteString(f.Text)
	}
	if joined.String() != samplePR {
		t.Error("the sections do not add up to the input byte for byte")
	}
}

func TestParseDiffEdges(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name, in, wantPath, wantErr string
	}{
		{name: "empty", in: ""},
		{name: "error text", in: "GraphQL: Could not resolve to a PullRequest\n", wantErr: "not a unified diff"},
		{name: "tab after a path with spaces", in: "diff --git a/my file b/my file\n--- a/my file\t\n+++ b/my file\t\n@@ -1 +1 @@\n-a\n+b\n", wantPath: "my file"},
		{name: "mode change", in: "diff --git a/run.sh b/run.sh\nold mode 100644\nnew mode 100755\n", wantPath: "run.sh"},
		{name: "unreadable header", in: "diff --git a/x b/y\nindex 1..2\n", wantErr: "cannot read the path"},
		{name: "no newline marker", in: "diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -1 +1 @@\n-a\n\\ No newline at end of file\n+b\n\\ No newline at end of file\n", wantPath: "f"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			files, err := parseDiff(tt.in)
			switch {
			case tt.wantErr != "":
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("error = %v, want one containing %q", err, tt.wantErr)
				}
			case err != nil:
				t.Fatal(err)
			case tt.wantPath == "":
				if len(files) != 0 {
					t.Fatalf("got %d files, want none", len(files))
				}
			case len(files) != 1 || files[0].Path != tt.wantPath:
				t.Fatalf("files = %+v, want one at %q", files, tt.wantPath)
			}
		})
	}
}

func TestSameChanges(t *testing.T) {
	t.Parallel()
	patch := func(context, added string) []fileDiff {
		files, err := parseDiff("diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -5,3 +5,3 @@\n " + context + "\n-old\n+" + added + "\n tail\n")
		if err != nil {
			t.Fatal(err)
		}
		return files
	}
	if !sameChanges(patch("ctx", "new"), patch("moved context", "new")) {
		t.Error("a patch whose only difference is its context lines must count as unchanged")
	}
	if sameChanges(patch("ctx", "new"), patch("ctx", "newer")) {
		t.Error("an edited added line must count as changed")
	}
}

