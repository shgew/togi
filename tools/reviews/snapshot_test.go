// pullHandler answers pr view with the given heads in turn and pr diff with diff.
func pullHandler(t *testing.T, diff string, heads ...string) func([]string) ([]byte, error) {
	t.Helper()
	views := 0
	return func(args []string) ([]byte, error) {
		switch {
		case args[0] == "pr" && args[1] == "view":
			head := heads[min(views, len(heads)-1)]
			views++
			return fmt.Appendf(nil, `{"headRefOid":%q,"baseRefOid":%q,"url":%q}`, head, baseSHA, prURL), nil
		case args[0] == "pr" && args[1] == "diff":
			if diff == "ERROR" {
				return nil, errors.New("gh pr diff: HTTP 502")
			}
			return []byte(diff), nil
		}
		return nil, fmt.Errorf("unexpected gh %v", args)
	}
}

func snapshotDir(tl tools) string {
	return filepath.Join(tl.tmp, "togi-review", "700-"+headSHA[:8])
}

func TestSnapshotFirstReview(t *testing.T) {
	t.Parallel()
	tl, g, _, out, _ := testTools(t, pullHandler(t, samplePR, headSHA, headSHA), nil)
	if err := runSnapshot(tl, []string{"700"}); err != nil {
		t.Fatal(err)
	}
	dir := snapshotDir(tl)
	if got := readFile(t, filepath.Join(dir, "pr.diff")); got != samplePR {
		t.Error("pr.diff is not the frozen diff byte for byte")
	}
	checkGolden(t, "snapshot/manifest.golden", readFile(t, filepath.Join(dir, "manifest.json")))
	checkGolden(t, "snapshot/summary.golden", strings.ReplaceAll(out.String(), dir, "<dir>"))
	// Hunk files: included files only, named by position in the manifest.
	var m manifest
	if err := json.Unmarshal([]byte(readFile(t, filepath.Join(dir, "manifest.json"))), &m); err != nil {
		t.Fatal(err)
	}
	var onDisk []string
	entries, err := os.ReadDir(filepath.Join(dir, "files"))
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		onDisk = append(onDisk, "files/"+e.Name())
	}
	var named []string
	for _, f := range m.included() {
		named = append(named, f.HunkFile)
		if got := readFile(t, filepath.Join(dir, f.HunkFile)); !strings.HasPrefix(got, "diff --git ") || !strings.Contains(samplePR, got) {
			t.Errorf("%s is not %s's section of the diff", f.HunkFile, f.Path)
		}
	}
	if diff := cmp.Diff(named, onDisk); diff != "" {
		t.Errorf("hunk files named in the manifest vs written (-named +written):\n%s", diff)
	}
	if _, err := os.Stat(filepath.Join(dir, "delta.diff")); err == nil {
		t.Error("a first review wrote delta.diff")
	}
	wantCalls := []string{"gh pr view 700 --json headRefOid,baseRefOid,url", "gh pr diff 700 --color=never --allow-escape-sequences", "gh pr view 700 --json headRefOid,baseRefOid,url"}
	if diff := cmp.Diff(wantCalls, g.joined()); diff != "" {
		t.Errorf("gh calls (-want +got):\n%s", diff)
	}
}

