func TestSameChangesMetadata(t *testing.T) {
	t.Parallel()
	parse := func(in string) []fileDiff {
		files, err := parseDiff(in)
		if err != nil {
			t.Fatal(err)
		}
		return files
	}
	hunk := "--- a/f\n+++ b/f\n@@ -5,3 +5,3 @@\n ctx\n-old\n+new\n tail\n"
	exec := parse("diff --git a/f b/f\nold mode 100644\nnew mode 100755\nindex 1..2\n" + hunk)
	plain := parse("diff --git a/f b/f\nindex 3..4 100644\n" + hunk)
	if sameChanges(exec, plain) || sameChanges(plain, exec) {
		t.Error("dropping an executable-bit change counted as context only")
	}
	if !sameChanges(exec, parse("diff --git a/f b/f\nold mode 100644\nnew mode 100755\nindex 5..6\n"+strings.Replace(hunk, "ctx", "moved context", 1))) {
		t.Error("the same mode change with moved context must count as unchanged")
	}
	if sameChanges(parse("diff --git a/f b/f\nold mode 100644\nnew mode 100755\n"), parse("diff --git a/f b/f\nold mode 100644\nnew mode 100644\n")) {
		t.Error("different new modes counted as the same")
	}
	if sameChanges(parse("diff --git a/f b/f\nnew file mode 100644\nindex 0000000..e69de29\n"), parse("diff --git a/f b/f\nnew file mode 100755\nindex 0000000..e69de29\n")) {
		t.Error("an empty file added with a different mode counted as the same")
	}
	noNewline := parse("diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -1 +1 @@\n-a\n+a\n\\ No newline at end of file\n")
	newline := parse("diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -1 +1 @@\n-a\n+a\n")
	if sameChanges(noNewline, newline) {
		t.Error("a patch that ends the file without a newline counted as the same as one that does not")
	}
	binary := func(old, new, payload string) []fileDiff {
		return parse("diff --git a/b.bin b/b.bin\nindex " + old + ".." + new + " 100644\nGIT binary patch\n" + payload + "\n")
	}
	if sameChanges(binary("1111111", "2222222", "literal 1"), binary("1111111", "3333333", "literal 1")) {
		t.Error("binary files with different resulting objects counted as the same")
	}
	if !sameChanges(binary("1111111", "2222222", "literal 1"), binary("4444444", "2222222", "delta 1")) {
		t.Error("a binary file with the same resulting object must count as unchanged whatever it was before")
	}
	noIndex := func(payload string) []fileDiff {
		return parse("diff --git a/b.bin b/b.bin\nGIT binary patch\n" + payload + "\n")
	}
	if sameChanges(noIndex("literal 1"), noIndex("literal 2")) || !sameChanges(noIndex("literal 1"), noIndex("literal 1")) {
		t.Error("without an index line binary files must compare by payload")
	}
}

