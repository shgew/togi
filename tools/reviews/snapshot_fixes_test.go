func TestLostEffects(t *testing.T) {
	t.Parallel()
	parse := func(in string) []fileDiff {
		files, err := parseDiff(in)
		if err != nil {
			t.Fatal(err)
		}
		return files
	}
	const file = "diff --git a/f b/f\n--- a/f\n+++ b/f\n"
	const hunkF = "@@ -5,3 +5,2 @@\n ctx\n-F = 1\n tail\n"
	const hunkG = "@@ -30,3 +29,2 @@\n ctx\n-G = 1\n tail\n"
	lostF := "@@ -6 +5,0 @@\n-F = 1\n"
	lostG := "@@ -31 +30,0 @@\n-G = 1\n"
	// The reversal of a commit that added F and G.
	two := parse(file + hunkF + hunkG)[0]
	// The reversal of a commit that removed a line, "was".
	removed := parse(file + "@@ -5,2 +5,3 @@\n ctx\n+was\n tail\n")[0]
	mode := parse("diff --git a/f b/f\nold mode 100755\nnew mode 100644\n")[0]
	binary := parse("diff --git a/f b/f\nindex 1111111..2222222 100644\nBinary files a/f and b/f differ\n")[0]
	binaryChanged := parse("diff --git a/f b/f\nindex 2222222..3333333 100644\nBinary files a/f and b/f differ\n")
	tests := []struct {
		name       string
		f          fileDiff
		base, head []fileDiff
		wantText   string // "" when nothing is lost
	}{
		{"both layers keep everything", two, nil, nil, ""},
		{"the base lost G, the head kept it", two, parse(file + lostG), nil, ""},
		{"the head lost G, the base kept it", two, nil, parse(file + lostG), ""},
		{"both lost G", two, parse(file + lostG), parse(file + lostG), file + hunkG},
		{"both lost F", two, parse(file + lostF), parse(file + lostF), file + hunkF},
		{"each lost a different hunk", two, parse(file + lostF), parse(file + lostG), ""},
		{"both lost both", two, parse(file + lostF + lostG), parse(file + lostF + lostG), file + hunkF + hunkG},
		{"unrelated change in both", two, parse(file + "@@ -50 +50 @@\n-x\n+y\n"), parse(file + "@@ -50 +50 @@\n-x\n+y\n"), ""},
		{"the line it removed came back in both", removed, parse(file + "@@ -30,0 +31 @@\n+was\n"), parse(file + "@@ -30,0 +31 @@\n+was\n"), file + "@@ -5,2 +5,3 @@\n ctx\n+was\n tail\n"},
		{"the line it removed stayed gone", removed, nil, parse(file + "@@ -30,0 +31 @@\n+was\n"), ""},
		{"mode changed in both", mode, parse("diff --git a/f b/f\nold mode 100755\nnew mode 100644\n"), parse("diff --git a/f b/f\nold mode 100755\nnew mode 100644\n"), mode.Text},
		{"mode changed only in the head", mode, nil, parse("diff --git a/f b/f\nold mode 100755\nnew mode 100644\n"), ""},
		{"only content changed since", mode, parse(file + "@@ -20 +20 @@\n-x\n+y\n"), parse(file + "@@ -20 +20 @@\n-x\n+y\n"), ""},
		{"binary differs in both", binary, binaryChanged, binaryChanged, binary.Text},
		{"binary differs only in the base", binary, binaryChanged, nil, ""},
	}
	for _, tt := range tests {
		got, ok := lostEffects(tt.f, tt.base, tt.head)
		if ok != (tt.wantText != "") || (ok && got.Text != tt.wantText) {
			t.Errorf("%s: lostEffects = %q, %t; want %q", tt.name, got.Text, ok, tt.wantText)
		}
	}
}

func TestSnapshotPreviousBase(t *testing.T) {
	t.Parallel()
	changed := "1:  aaa1111 ! 1:  bbb1111 edit\n"
	patches := map[string]string{
		"aaa1111^ aaa1111": onePatch("b.go", "ctx", "v1"),
		"bbb1111^ bbb1111": onePatch("b.go", "ctx", "v2"),
	}
	legacy := previousBodyVerdict(2, "", "")
	t.Run("supplied base replaces the fallback", func(t *testing.T) {
		t.Parallel()
		tl, git := reReviewTools(t, legacy, changed, patches)
		if err := runSnapshot(tl, []string{"--previous", previousURL, "--previous-base", oldBaseSHA, "700"}); err != nil {
			t.Fatal(err)
		}
		dir := snapshotDir(tl)
		m, err := readManifest(dir)
		if err != nil {
			t.Fatal(err)
		}
		if m.Fallback != "" || m.Previous == nil || m.Previous.BaseSHA != oldBaseSHA || m.Previous.HeadSHA != oldHeadSHA {
			t.Errorf("manifest = fallback %q, previous %+v; want the supplied base used", m.Fallback, m.Previous)
		}
		calls := git.joined()
		wantFetch := "git fetch --quiet origin " + oldBaseSHA + " " + oldHeadSHA + " " + baseSHA + " " + headSHA
		wantRange := "git range-diff --no-patch --no-color " + oldBaseSHA + ".." + oldHeadSHA + " " + baseSHA + ".." + headSHA
		if len(calls) < 2 || calls[0] != wantFetch || calls[1] != wantRange {
			t.Errorf("git calls = %q, want the fetch and range-diff of both ranges", calls)
		}
		if len(m.Files) != 1 || m.Files[0].Path != "b.go" {
			t.Errorf("files = %+v, want the delta's b.go", m.Files)
		}
		if got := readFile(t, filepath.Join(dir, "delta.diff")); got != onePatch("b.go", "ctx", "v2") {
			t.Errorf("delta.diff = %q", got)
		}
	})
	t.Run("a recovered legacy record without a verdict does not carry forward", func(t *testing.T) {
		t.Parallel()
		tl, _ := reReviewTools(t, legacy, "1:  aaa1111 = 1:  bbb1111 one\n", nil)
		if err := runSnapshot(tl, []string{"--previous", previousURL, "--previous-base", oldBaseSHA, "700"}); err != nil {
			t.Fatal(err)
		}
		m, err := readManifest(snapshotDir(tl))
		if err != nil {
			t.Fatal(err)
		}
		if m.Fallback != "" || m.CarryForward || len(m.Patches) != 1 || m.Patches[0].Status != "unchanged" {
			t.Errorf("manifest = fallback %q, carry %t, patches %+v; want an unchanged delta that is not carried forward", m.Fallback, m.CarryForward, m.Patches)
		}
	})
	for _, version := range []int{1, 2} {
		t.Run(fmt.Sprintf("a recovered version %d record with an explicit success verdict carries forward", version), func(t *testing.T) {
			t.Parallel()
			tl, _ := reReviewTools(t, previousBodyVerdict(version, "", "success"), "1:  aaa1111 = 1:  bbb1111 one\n", nil)
			if err := runSnapshot(tl, []string{"--previous", previousURL, "--previous-base", oldBaseSHA, "700"}); err != nil {
				t.Fatal(err)
			}
			m, err := readManifest(snapshotDir(tl))
			if err != nil {
				t.Fatal(err)
			}
			if m.Fallback != "" || !m.CarryForward || m.Previous == nil || m.Previous.Verdict != "success" || m.Previous.BaseSHA != oldBaseSHA {
				t.Errorf("manifest = fallback %q, carry %t, previous %+v; want carry-forward on the recovered base", m.Fallback, m.CarryForward, m.Previous)
			}
		})
	}

	t.Run("unrecovered base falls back", func(t *testing.T) {
		t.Parallel()
		tl, git := reReviewTools(t, legacy, "", nil)
		if err := runSnapshot(tl, []string{"--previous", previousURL, "700"}); err != nil {
			t.Fatal(err)
		}
		m, err := readManifest(snapshotDir(tl))
		if err != nil {
			t.Fatal(err)
		}
		if m.Fallback == "" || m.Previous == nil || m.Previous.BaseSHA != "" || len(git.calls) != 0 {
			t.Errorf("fallback %q, previous %+v, git calls %v; want the whole layer and no git", m.Fallback, m.Previous, git.joined())
		}
	})
	t.Run("a base the record contradicts", func(t *testing.T) {
		t.Parallel()
		tl, _ := reReviewTools(t, previousBody(3, oldBaseSHA), changed, patches)
		err := runSnapshot(tl, []string{"--previous", previousURL, "--previous-base", strings.Repeat("3", 40), "700"})
		if err == nil || !strings.Contains(err.Error(), "names base "+oldBaseSHA) {
			t.Fatalf("error = %v, want a refusal of the contradicting base", err)
		}
	})
	t.Run("the record's own base is accepted", func(t *testing.T) {
		t.Parallel()
		tl, _ := reReviewTools(t, previousBody(3, oldBaseSHA), changed, patches)
		if err := runSnapshot(tl, []string{"--previous", previousURL, "--previous-base", oldBaseSHA, "700"}); err != nil {
			t.Fatal(err)
		}
	})
	for name, args := range map[string][]string{
		"without --previous": {"--previous-base", oldBaseSHA, "700"},
		"not a full SHA":     {"--previous", previousURL, "--previous-base", "2222222", "700"},
		"upper case":         {"--previous", previousURL, "--previous-base", strings.ToUpper(baseSHA), "700"},
		"for a snapshot dir": {"--previous-base", oldBaseSHA, "--cover", "-", "some-dir"},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			tl, _, _, _, _ := testTools(t, nil, nil)
			if err := runSnapshot(tl, args); err == nil || !strings.Contains(err.Error(), "usage: reviews snapshot") {
				t.Fatalf("error = %v, want usage", err)
			}
		})
	}
}

// addedFile is the patch that adds a file with the given lines.
func addedFile(name string, lines ...string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "diff --git a/%[1]s b/%[1]s\nnew file mode 100644\nindex 0000000..1111111\n--- /dev/null\n+++ b/%[1]s\n@@ -0,0 +1,%d @@\n", name, len(lines))
	for _, l := range lines {
		b.WriteString("+" + l + "\n")
	}
	return b.String()
}

// TestSnapshotDeltaGeneratedStatusIsTheHeads has two patches touch one path in one delta: whether it is generated is what the frozen head holds, not what any single patch showed.
func TestSnapshotDeltaGeneratedStatusIsTheHeads(t *testing.T) {
	t.Parallel()
	marker := strings.TrimSuffix(generatedMarker, "\n")
	dropMarker := "diff --git a/gen/c.go b/gen/c.go\nindex 1111111..2222222 100644\n--- a/gen/c.go\n+++ b/gen/c.go\n@@ -1,3 +1,2 @@\n-" + marker + "\n package gen\n var a = 1\n"
	addMarker := "diff --git a/gen/d.go b/gen/d.go\nindex 1111111..2222222 100644\n--- a/gen/d.go\n+++ b/gen/d.go\n@@ -1,2 +1,3 @@\n+" + marker + "\n package gen\n var a = 1\n"
	rangeDiff := "-:  ------- > 1:  bbb1111 add generated c\n-:  ------- > 2:  bbb2222 make c handwritten\n-:  ------- > 3:  bbb3333 add handwritten d\n-:  ------- > 4:  bbb4444 make d generated\n"
	patches := map[string]string{
		"bbb1111^ bbb1111": addedFile("gen/c.go", marker, "package gen", "var a = 1"),
		"bbb2222^ bbb2222": dropMarker,
		"bbb3333^ bbb3333": addedFile("gen/d.go", "package gen", "var a = 1"),
		"bbb4444^ bbb4444": addMarker,
	}
	var reads []string
	tl, _ := reReview{
		body: previousBody(3, oldBaseSHA), rangeDiff: rangeDiff, patches: patches,
		contents: map[string]string{
			"gen/c.go": "package gen\nvar a = 1\n",
			"gen/d.go": marker + "\npackage gen\nvar a = 1\n",
		},
		onAPI: func(args []string) {
			if last := args[len(args)-1]; strings.Contains(last, "/contents/") {
				reads = append(reads, last)
			}
		},
	}.tools(t)
	if err := runSnapshot(tl, []string{"--previous", previousURL, "700"}); err != nil {
		t.Fatal(err)
	}
	m, err := readManifest(snapshotDir(tl))
	if err != nil {
		t.Fatal(err)
	}
	type row struct{ Path, Exclusion string }
	var got []row
	for _, f := range m.Files {
		got = append(got, row{f.Path, f.Exclusion})
	}
	want := []row{{"gen/c.go", ""}, {"gen/d.go", "generated"}}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("exclusions (-want +got; the head's content decides, not a marker an earlier patch added):\n%s", diff)
	}
	if m.IncludedFiles != 1 || m.Files[0].HunkFile == "" {
		t.Errorf("F = %d, files = %+v; want the handwritten gen/c.go reviewed", m.IncludedFiles, m.Files)
	}
	if len(reads) != 2 || !strings.Contains(reads[0], "gen/c.go") || !strings.Contains(reads[1], "gen/d.go") {
		t.Errorf("file reads = %q, want gen/c.go and gen/d.go read at the frozen head", reads)
	}
}
