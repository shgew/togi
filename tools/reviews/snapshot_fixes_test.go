	if err != nil {
		t.Fatal(err)
	}
	want := []patchStatus{
		{Old: "aaa1111", Subject: "A moved into the base", Status: "removed"},
		{Old: "aaa2222", New: "bbb2222", Subject: "B stays", Status: "unchanged"},
	}
