func TestParseDiffQuotedHeaderOnly(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name, in, wantPath, wantStatus, wantExclusion string
		wantBinary                                    bool
	}{
		{
			name: "binary file", wantPath: "café.png", wantStatus: "added", wantBinary: true, wantExclusion: "binary",
			in: "diff --git \"a/caf\\303\\251.png\" \"b/caf\\303\\251.png\"\nnew file mode 100644\nindex 0000000..8888888\nBinary files /dev/null and \"b/caf\\303\\251.png\" differ\n",
		},
		{
			name: "binary patch", wantPath: "café.png", wantStatus: "modified", wantBinary: true, wantExclusion: "binary",
			in: "diff --git \"a/caf\\303\\251.png\" \"b/caf\\303\\251.png\"\nindex 1111111..2222222 100644\nGIT binary patch\nliteral 1\nIcmZ\n\nliteral 0\nHcmV?d00001\n\n",
		},
		{
			name: "empty file with a control character", wantPath: "a\tb", wantStatus: "added",
			in: "diff --git \"a/a\\tb\" \"b/a\\tb\"\nnew file mode 100644\nindex 0000000..e69de29\n",
		},
		{
			name: "mode change", wantPath: "süß.sh", wantStatus: "modified",
			in: "diff --git \"a/s\\303\\274\\303\\237.sh\" \"b/s\\303\\274\\303\\237.sh\"\nold mode 100644\nnew mode 100755\n",
		},
		{
			name: "deleted empty file with a quote", wantPath: `say "hi"`, wantStatus: "deleted",
			in: "diff --git \"a/say \\\"hi\\\"\" \"b/say \\\"hi\\\"\"\ndeleted file mode 100644\nindex e69de29..0000000\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			files, err := parseDiff(tt.in)
			if err != nil {
				t.Fatal(err)
			}
			if len(files) != 1 {
				t.Fatalf("got %d files, want 1", len(files))
			}
			f := files[0]
			if f.Path != tt.wantPath || f.Status != tt.wantStatus || f.Binary != tt.wantBinary || excludedReason(f) != tt.wantExclusion {
				t.Errorf("file = path %q, status %q, binary %t, exclusion %q; want %q, %q, %t, %q", f.Path, f.Status, f.Binary, excludedReason(f), tt.wantPath, tt.wantStatus, tt.wantBinary, tt.wantExclusion)
			}
		})
	}
	for _, bad := range []string{
		"diff --git \"a/x\" \"b/y\"\nindex 1..2\n",
		"diff --git \"a/x\" b/x\nindex 1..2\n",
		"diff --git \"a/unterminated b/unterminated\nindex 1..2\n",
	} {
		if _, err := parseDiff(bad); err == nil || !strings.Contains(err.Error(), "cannot read the path") {
			t.Errorf("parseDiff(%q) error = %v, want a path refusal", bad, err)
		}
	}
}

