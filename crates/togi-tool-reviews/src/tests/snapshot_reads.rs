/// A too-large pull request whose diff git builds in a temporary repository, answering `cat-file` with
/// `cat_file`.
fn local_harness(cat_file: Output) -> Harness {
    let gh = pull_fake(
        "TOO_LARGE",
        contents(&[
            ("x/dir", MARKED),
            ("x/link.go", MARKED),
            ("x/new\nline.go", MARKED),
        ]),
        frozen(),
    );
    let git: Handler = Box::new(|args: &[String]| {
        if args == ["remote", "get-url", "origin"] {
            return Ok(format!("{ORIGIN_URL}\n").into_bytes());
        }
        Err(fail(&format!("unexpected git {args:?}")))
    });
    let mut h = Harness::new(Some(Box::new(gh)), Some(git));
    let mut answer: IsolatedAnswer = Box::new(move |args: &[String]| match args[0].as_str() {
        "diff" => Some(Ok(LOCAL_DIFF.as_bytes().to_vec())),
        "cat-file" => Some(cat_file.clone()),
        _ => None,
    });
    h.fake.isolated = Some(Box::new(move |_: &Path, args: &[String], _: &[u8]| {
        answer(args).unwrap_or_else(|| Ok(Vec::new()))
    }));
    h
}

/// The temporary repository answers every regular file it holds; GitHub is asked only for a path that is
/// not one there, such as a tree or a symlink, which GitHub reads through to its target, or that
/// `cat-file --batch` cannot name.
#[test]
fn snapshot_too_large_diff_reads_files_from_its_repository() {
    let out = format!(
        "100644 {} blob {}\n{MARKED}\n{HEAD_SHA}:x/gone.go missing\n040000 {} tree 0\n\n120000 {} blob 11\nx/target.go\n",
        "e".repeat(40),
        MARKED.len(),
        "f".repeat(40),
        "d".repeat(40),
    );
    let mut h = local_harness(Ok(out.into_bytes()));
    snapshot(&mut h, &["700"]).expect("snapshot");
    assert_eq!(
        rows(&[
            ("x/gen.go", "generated"),
            ("x/gone.go", ""),
            ("x/dir", "generated"),
            ("x/link.go", "generated"),
            ("x/new\nline.go", "generated"),
        ]),
        exclusions(&h)
    );
    assert_eq!(
        format!(
            "{HEAD_SHA}:x/gen.go\n{HEAD_SHA}:x/gone.go\n{HEAD_SHA}:x/dir\n{HEAD_SHA}:x/link.go\n"
        ),
        lossy(&h.fake.isolated_inputs[3]),
        "one cat-file reads every path it can name"
    );
    assert_eq!(
        vec![
            view_call(),
            diff_call(),
            view_call(),
            read_call("x/dir"),
            read_call("x/link.go"),
            read_call("x/new%0Aline.go"),
            view_call(),
        ],
        gh_calls(&h)
    );
}

#[test_case(Err(CommandError::new("injected failure")), "injected failure"; "cat-file fails")]
#[test_case(Ok(Vec::new()), "read x/gen.go at aaaaaaaa from the temporary repository: git cat-file printed no object for it"; "cat-file prints nothing")]
#[test_case(Ok(b"100644 eeee blob 99\nshort\n".to_vec()), "git cat-file printed no object"; "cat-file output cut short")]
fn snapshot_too_large_diff_local_read_failure(cat_file: Output, want: &str) {
    let mut h = local_harness(cat_file);
    let error = snapshot(&mut h, &["700"])
        .expect_err("snapshot accepted")
        .render();
    assert!(
        error.contains(want) && error.contains("from the temporary repository"),
        "error = {error}, want {want:?} in reading from the temporary repository"
    );
    assert!(
        !Path::new(&snapshot_dir(&h)).exists(),
        "a refused snapshot left a directory behind"
    );
    let left: Vec<String> = std::fs::read_dir(h.tmp.path())
        .expect("read dir")
        .map(|entry| {
            entry
                .expect("entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    assert!(
        left.is_empty(),
        "the temporary repository was left behind: {left:?}"
    );
}
