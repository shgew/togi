const MARKED: &str = "// Code generated by tool; DO NOT EDIT.\npackage x\n";

fn view_call() -> String {
    "gh pr view 700 --json headRefOid,baseRefOid,url".to_owned()
}

fn diff_call() -> String {
    "gh pr diff 700 --color=never --allow-escape-sequences".to_owned()
}

fn read_call(name: &str) -> String {
    format!(
        "gh api -H Accept: application/vnd.github.raw+json repos/shgew/togi/contents/{name}?ref={HEAD_SHA}"
    )
}

/// Each manifest file's path and exclusion.
fn exclusions(h: &Harness) -> Vec<(String, String)> {
    manifest(h)
        .files
        .into_iter()
        .map(|f| (f.path, f.exclusion))
        .collect()
}

fn rows(rows: &[(&str, &str)]) -> Vec<(String, String)> {
    rows.iter()
        .map(|&(path, exclusion)| (path.to_owned(), exclusion.to_owned()))
        .collect()
}

/// A diff modifying `count` files, `f000.go` on, one line each.
fn modified_files(count: usize) -> String {
    (0..count)
        .map(|i| {
            format!(
                "diff --git a/f{i:03}.go b/f{i:03}.go\nindex 1111111..2222222 100644\n--- a/f{i:03}.go\n+++ b/f{i:03}.go\n@@ -1 +1 @@\n-a\n+b\n"
            )
        })
        .collect::<Vec<_>>()
        .concat()
}

#[test_case(250, 3; "several hundred files")]
#[test_case(100, 1; "one full batch")]
#[test_case(101, 2; "one file past a batch")]
fn snapshot_reads_files_in_bounded_batches(count: usize, want_batches: usize) {
    let diff = modified_files(count);
    let files: HashMap<String, String> = (0..count)
        .map(|i| {
            let body = if i % 3 == 0 { MARKED } else { "package x\n" };
            (format!("f{i:03}.go"), body.to_owned())
        })
        .collect();
    let mut h = Harness::new(
        Some(Box::new(pull_fake(&diff, files.clone(), frozen()))),
        None,
    );
    snapshot(&mut h, &["700"]).expect("snapshot");
    let batches: Vec<usize> = h
        .fake
        .gh_calls
        .iter()
        .filter(|args| args[1] == "graphql")
        .map(|args| batch_reads(args).len())
        .collect();
    assert!(
        batches.len() == want_batches
            && batches.iter().all(|&n| n <= HEAD_BATCH)
            && batches.iter().sum::<usize>() == count,
        "batches of {batches:?} for {count} files, want {want_batches} of at most {HEAD_BATCH}"
    );
    assert_eq!(
        3 + 1 + want_batches,
        h.fake.gh_calls.len(),
        "three looks at the pull request, its diff and the batches, with no file read on its own: {:?}",
        gh_calls(&h)
    );
    let generated = exclusions(&h)
        .iter()
        .filter(|(_, exclusion)| exclusion == "generated")
        .count();
    assert_eq!(count.div_ceil(3), generated, "generated files excluded");
    // Reading each file on its own, as the snapshot did before it batched, excludes the same files.
    let mut pr = pull_fake(&diff, files, frozen());
    let mut one_by_one = Harness::new(
        Some(Box::new(move |args: &[String]| {
            if args[1] == "graphql" {
                return Err(fail("gh: GraphQL unavailable"));
            }
            pr(args)
        })),
        None,
    );
    snapshot(&mut one_by_one, &["700"]).expect("snapshot");
    assert_eq!(exclusions(&one_by_one), exclusions(&h));
    assert_eq!(
        count,
        gh_calls(&one_by_one)
            .iter()
            .filter(|call| call.starts_with("gh api -H "))
            .count(),
        "each file read on its own once its batch failed"
    );
}

/// What GitHub answers for `x/a.go`, whose bytes carry the generated marker.
fn uncertain_answer(kind: &str) -> Output {
    let size = MARKED.len();
    let answer = |entry: serde_json::Value| {
        Ok(json!({"data": {"repository": {"object": {"p0": entry}}}})
            .to_string()
            .into_bytes())
    };
    let file = |object: serde_json::Value| answer(json!({"mode": 0o100_644, "object": object}));
    let text = |text: &str, binary: serde_json::Value, truncated: bool| json!({"__typename": "Blob", "byteSize": size, "isBinary": binary, "isTruncated": truncated, "text": text});
    match kind {
        "null text" => file(
            json!({"__typename": "Blob", "byteSize": size, "isBinary": false, "isTruncated": false, "text": null}),
        ),
        "truncated" => file(text("package x\n", json!(false), true)),
        "binary" => file(
            json!({"__typename": "Blob", "byteSize": size, "isBinary": true, "isTruncated": false, "text": null}),
        ),
        "binary unknown" => file(text(MARKED, serde_json::Value::Null, false)),
        "replaced bytes" => {
            let replaced = MARKED.replacen("//", "\u{FFFD}", 1);
            file(
                json!({"__typename": "Blob", "byteSize": replaced.len(), "isBinary": false, "isTruncated": false, "text": replaced}),
            )
        }
        "other size" => file(text("package x\n", json!(false), false)),
        // GitHub's contents request answers a symlink to a file with the file, not with the link's target
        // name, which is all the blob holds.
        "symlink" => answer(json!({"mode": 0o120_000, "object": blob("x/target.go")})),
        "not a file" => answer(json!({"mode": 0o040_000, "object": {"__typename": "Tree"}})),
        "no object" => answer(json!({"mode": 0o100_644, "object": null})),
        "null entry" => Ok(
            json!({"data": {"repository": {"object": {"p0": null}}}, "errors": [{"message": "timeout"}]})
                .to_string()
                .into_bytes(),
        ),
        "no commit" => Ok(json!({"data": {"repository": {"object": null}}})
            .to_string()
            .into_bytes()),
        "no repository" => Ok(
            json!({"data": {"repository": null}, "errors": [{"message": "timeout"}]})
                .to_string()
                .into_bytes(),
        ),
        "no alias" => Ok(json!({"data": {"repository": {"object": {}}}})
            .to_string()
            .into_bytes()),
        "undecodable" => Ok(b"<html>".to_vec()),
        "failed request" => Err(fail("gh: HTTP 502")),
        _ => panic!("unknown answer {kind}"),
    }
}

/// Any answer that is not certainly the file's bytes sends the file to a byte-for-byte read of its own, so
/// the exclusion is the same as reading it whole.
#[test_case("null text")]
#[test_case("truncated")]
#[test_case("binary")]
#[test_case("binary unknown")]
#[test_case("replaced bytes")]
#[test_case("other size")]
#[test_case("symlink")]
#[test_case("not a file")]
#[test_case("no object")]
#[test_case("null entry")]
#[test_case("no commit")]
#[test_case("no repository")]
#[test_case("no alias")]
#[test_case("undecodable")]
#[test_case("failed request")]
fn snapshot_reads_an_uncertain_answer_byte_for_byte(kind: &str) {
    let answer = uncertain_answer(kind);
    let mut pr = pull_fake(
        &one_patch("x/a.go", "ctx", "v"),
        contents(&[("x/a.go", MARKED)]),
        frozen(),
    );
    let gh: Handler = Box::new(move |args: &[String]| {
        if args[1] == "graphql" {
            return answer.clone();
        }
        pr(args)
    });
    let mut h = Harness::new(Some(gh), None);
    snapshot(&mut h, &["700"]).expect("snapshot");
    assert_eq!(rows(&[("x/a.go", "generated")]), exclusions(&h));
    assert_eq!(
        vec![
            view_call(),
            diff_call(),
            view_call(),
            "gh graphql x/a.go".to_owned(),
            read_call("x/a.go"),
            view_call(),
        ],
        gh_calls(&h)
    );
}

/// A path the head lacks fails GitHub's whole batch; each of its files is then read on its own, and the
/// missing one stays in the review.
#[test]
fn snapshot_missing_file_stays_included() {
    let mut h = Harness::new(
        Some(Box::new(pull_fake(
            &one_patch("x/a.go", "ctx", "v"),
            HashMap::new(),
            frozen(),
        ))),
        None,
    );
    snapshot(&mut h, &["700"]).expect("snapshot");
    assert_eq!(rows(&[("x/a.go", "")]), exclusions(&h));
    assert_eq!(
        vec![
            view_call(),
            diff_call(),
            view_call(),
            "gh graphql x/a.go".to_owned(),
            read_call("x/a.go"),
            view_call(),
        ],
        gh_calls(&h)
    );
}

/// A file the diff deletes may be missing at the head, which would fail a whole batch, so it is read on its
/// own and the batch asks only for the others.
#[test]
fn deleted_file_is_read_on_its_own() {
    let file = |path: &str, status: &str| FileDiff {
        path: path.to_owned(),
        status: status.to_owned(),
        ..FileDiff::default()
    };
    let (kept, deleted) = (file("x/a.go", "modified"), file("x/gone.go", "deleted"));
    let mut h = Harness::new(
        Some(Box::new(pull_fake(
            "",
            contents(&[("x/a.go", MARKED)]),
            frozen(),
        ))),
        None,
    );
    let read = read_at_head(
        &mut h.fake,
        "shgew/togi",
        HEAD_SHA,
        &[&deleted, &kept],
        &HeadFiles::Remote,
    )
    .expect("read");
    assert_eq!(vec![None, Some(MARKED.as_bytes().to_vec())], read);
    assert_eq!(
        vec!["gh graphql x/a.go".to_owned(), read_call("x/gone.go")],
        gh_calls(&h)
    );
}

