pub(crate) type Hook = Box<dyn FnMut(&[String])>;

/// Fakes a pull request that moved from `OLD_HEAD_SHA` to `HEAD_SHA`: the previous record's comment,
/// git's range-diff and patches, and the frozen head's files. Empty fields take the defaults of the
/// common case.
#[derive(Default)]
pub(crate) struct ReReview {
    pub body: String,
    pub range_diff: String,
    /// Answers git diff by `<from> <to>` for a patch, and by `<commit> -- <path>` for the changes since a
    /// removed commit, as the new head leaves the file. A key may name the target, `base` or `head`,
    /// before the `--`; several paths are joined by a space.
    pub patches: HashMap<String, String>,
    pub diff: Option<String>,
    pub contents: Option<HashMap<String, String>>,
    pub view: Option<View>,
    /// The previous record's author; `robotogi[bot]` when empty.
    pub login: String,
    /// The pull request's comments as the API lists them, pages of objects; `[[]]` when empty.
    pub comments: String,
    /// Run before a gh api or git call is answered.
    pub on_api: Option<Hook>,
    pub on_git: Option<Hook>,
    /// The removed commits the new base contains itself.
    pub ancestors: HashSet<String>,
    /// The new base's log of a removed commit: what git log -p prints, one NUL-led patch per commit.
    pub logs: HashMap<String, String>,
    /// Makes the ancestry check of a commit fail with the error.
    pub ancestry_err: HashMap<String, CommandError>,
}

impl ReReview {
    pub(crate) fn new(body: String, range_diff: &str, patches: &[(&str, &str)]) -> Self {
        Self {
            body,
            range_diff: range_diff.to_owned(),
            patches: contents(patches),
            ..Self::default()
        }
    }

    pub(crate) fn harness(self) -> Harness {
        let Self {
            body,
            range_diff,
            patches,
            diff,
            contents,
            view,
            login,
            comments,
            mut on_api,
            mut on_git,
            ancestors,
            logs,
            ancestry_err,
        } = self;
        let mut pr = pull_fake(
            diff.as_deref().unwrap_or(SAMPLE_PR),
            contents.unwrap_or_else(sample_contents),
            view.unwrap_or_else(frozen),
        );
        let login = if login.is_empty() {
            "robotogi[bot]".to_owned()
        } else {
            login
        };
        let gh: Handler = Box::new(move |args: &[String]| {
            if args[0] == "api" {
                if let Some(on_api) = on_api.as_mut() {
                    on_api(args);
                }
                if args[1] == "repos/shgew/togi/issues/comments/4242" {
                    return Ok(json!({"body": body, "user": {"login": login}})
                        .to_string()
                        .into_bytes());
                }
                if args
                    .last()
                    .is_some_and(|a| a == "repos/shgew/togi/issues/700/comments")
                {
                    let pages = if comments.is_empty() {
                        "[[]]"
                    } else {
                        &comments
                    };
                    return Ok(pages.as_bytes().to_vec());
                }
            }
            pr(args)
        });
        let git: Handler = Box::new(move |args: &[String]| {
            if let Some(on_git) = on_git.as_mut() {
                on_git(args);
            }
            let unexpected = || Err(fail(&format!("unexpected git {args:?}")));
            match args[0].as_str() {
                "fetch" => Ok(Vec::new()),
                "range-diff" => Ok(range_diff.as_bytes().to_vec()),
                "merge-base" => {
                    if args[1] != "--is-ancestor" || args[3] != BASE_SHA {
                        return unexpected();
                    }
                    if let Some(error) = ancestry_err.get(&args[2]) {
                        return Err(error.clone());
                    }
                    if ancestors.contains(&args[2]) {
                        return Ok(Vec::new());
                    }
                    Err(CommandError::exit("git merge-base", 1))
                }
                "log" => {
                    let Some(at) = args.iter().position(|a| a == "--") else {
                        return unexpected();
                    };
                    let Some((commit, base)) = args[at.saturating_sub(1)].split_once("..") else {
                        return unexpected();
                    };
                    if at < 1 || base != BASE_SHA || args.len() == at + 1 {
                        return unexpected();
                    }
                    Ok(logs
                        .get(commit)
                        .map(|log| log.as_bytes().to_vec())
                        .unwrap_or_default())
                }
                "diff" => {
                    let n = args.len();
                    if let Some(at) = args.iter().position(|a| a == "--") {
                        let target = match args[at - 1].as_str() {
                            BASE_SHA => "base",
                            HEAD_SHA => "head",
                            other => {
                                return Err(fail(&format!(
                                    "changes since a removed commit were read against {other}, neither the frozen base nor head: {args:?}"
                                )));
                            }
                        };
                        let names: Vec<&str> = args[at + 1..]
                            .iter()
                            .map(|a| a.strip_prefix(":(literal)").unwrap_or(a))
                            .collect();
                        let name = names.join(" ");
                        for key in [
                            format!("{} {target} -- {name}", args[at - 2]),
                            format!("{} -- {name}", args[at - 2]),
                        ] {
                            if let Some(p) = patches.get(&key) {
                                return Ok(p.as_bytes().to_vec());
                            }
                        }
                        return unexpected();
                    }
                    patches
                        .get(&format!("{} {}", args[n - 2], args[n - 1]))
                        .map_or_else(unexpected, |p| Ok(p.as_bytes().to_vec()))
                }
                _ => unexpected(),
            }
        });
        Harness::new(Some(gh), Some(git))
    }
}

/// A harness for a pull request that moved from `OLD_HEAD_SHA` to `HEAD_SHA` with the previous record's body.
pub(crate) fn re_review(body: String, range_diff: &str, patches: &[(&str, &str)]) -> Harness {
    ReReview::new(body, range_diff, patches).harness()
}

/// A previous record's comment: a version 3 record is a success.
pub(crate) fn previous_body(version: i64, base: &str) -> String {
    previous_body_verdict(version, base, "success")
}

/// A previous record's comment; a verdict is written whenever one is given, in any version, and version 3
/// always writes it.
pub(crate) fn previous_body_verdict(version: i64, base: &str, verdict: &str) -> String {
    let mut b = format!(
        r#"{{"version":{version},"head_sha":{},"findings":[]"#,
        quote(OLD_HEAD_SHA)
    );
    if !base.is_empty() {
        let _ = write!(b, r#","base_sha":{}"#, quote(base));
    }
    if !verdict.is_empty() || version >= 3 {
        let _ = write!(b, r#","verdict":{}"#, quote(verdict));
    }
    format!("## Review record\n\n<!-- togi-review {b}}} -->\n")
}

pub(crate) fn patch_status(
    old: &str,
    new: &str,
    subject: &str,
    status: &str,
    context_only: bool,
) -> PatchStatus {
    PatchStatus {
        old: old.to_owned(),
        new: new.to_owned(),
        subject: subject.to_owned(),
        status: status.to_owned(),
        context_only,
    }
}

pub(crate) fn paths(m: &Manifest) -> Vec<&str> {
    m.files.iter().map(|f| f.path.as_str()).collect()
}

#[test]
fn snapshot_re_review_classifies_patches() {
    let range_diff = "1:  aaa1111 = 1:  bbb1111 stays the same
2:  aaa2222 ! 2:  bbb2222 only context moved
3:  aaa3333 ! 3:  bbb3333 edited added line
-:  ------- > 4:  bbb4444 new commit
4:  aaa5555 < -:  ------- dropped commit
";
    let mut h = re_review(
        previous_body(3, OLD_BASE_SHA),
        range_diff,
        &[
            ("aaa2222^ aaa2222", &one_patch("a.go", "before", "x")),
            ("bbb2222^ bbb2222", &one_patch("a.go", "other context", "x")),
            ("aaa3333^ aaa3333", &one_patch("b.go", "ctx", "v1")),
            ("bbb3333^ bbb3333", &one_patch("b.go", "ctx", "v2")),
            ("bbb4444^ bbb4444", &one_patch("c.go", "ctx", "fresh")),
            ("aaa5555 aaa5555^", &one_patch("d.go", "ctx", "gone")),
            // The new head replaced what the dropped commit added to d.go by what it had removed, so its effect
            // is really gone.
            (
                "aaa5555 -- d.go",
                "diff --git a/d.go b/d.go\n--- a/d.go\n+++ b/d.go\n@@ -6 +6 @@\n-old\n+gone\n",
            ),
        ],
    );
    snapshot(&mut h, &["--previous", PREVIOUS_URL, "700"]).expect("snapshot");
    let m = manifest(&h);
    let want = vec![
        patch_status("aaa1111", "bbb1111", "stays the same", "unchanged", false),
        patch_status(
            "aaa2222",
            "bbb2222",
            "only context moved",
            "unchanged",
            true,
        ),
        patch_status("aaa3333", "bbb3333", "edited added line", "changed", false),
        patch_status("", "bbb4444", "new commit", "added", false),
        patch_status("aaa5555", "", "dropped commit", "removed", false),
    ];
    assert_eq!(want, m.patches);
    assert!(
        !m.carry_forward,
        "a delta with changed, added and removed patches carried forward"
    );
    assert_eq!(
        vec!["b.go", "c.go", "d.go"],
        paths(&m),
        "the context-only and unchanged patches are not in the delta"
    );
    let want_delta = one_patch("b.go", "ctx", "v2")
        + &one_patch("c.go", "ctx", "fresh")
        + &one_patch("d.go", "ctx", "gone");
    assert_eq!(want_delta, snapshot_file(&h, "delta.diff"));
    assert_eq!(
        SAMPLE_PR,
        snapshot_file(&h, "pr.diff"),
        "pr.diff must stay the whole frozen diff on a re-review"
    );
    assert!(
        !m.small && m.pr_files == 8,
        "the rule must measure the whole diff, not the delta"
    );
    let want_fetch =
        format!("git fetch --quiet origin {OLD_BASE_SHA} {OLD_HEAD_SHA} {BASE_SHA} {HEAD_SHA}");
    assert_eq!(want_fetch, h.fake.git_joined()[0]);
    let previous = m.previous.as_ref().expect("previous");
    assert_eq!(
        (PREVIOUS_URL, OLD_HEAD_SHA, OLD_BASE_SHA),
        (
            previous.url.as_str(),
            previous.head_sha.as_str(),
            previous.base_sha.as_str()
        )
    );
}

