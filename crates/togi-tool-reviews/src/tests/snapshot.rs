pub(crate) const ORIGIN_URL: &str = "https://example.test/shgew/togi.git";

pub(crate) type IsolatedAnswer = Box<dyn FnMut(&[String]) -> Option<Output>>;

/// A harness for a too-large pull request whose git answers the origin URL and whose isolated git answers
/// like a working repository, except where `isolated` answers first.
fn local_diff_harness(gh: Handler, mut isolated: Option<IsolatedAnswer>) -> Harness {
    let git: Handler = Box::new(|args: &[String]| {
        if args == ["remote", "get-url", "origin"] {
            return Ok(format!("{ORIGIN_URL}\n").into_bytes());
        }
        Err(fail(&format!("unexpected git {args:?}")))
    });
    let mut h = Harness::new(Some(gh), Some(git));
    h.fake.isolated = Some(Box::new(move |_dir: &Path, args: &[String]| {
        if let Some(answer) = isolated.as_mut().and_then(|isolated| isolated(args)) {
            return answer;
        }
        if args[0] == "diff" {
            return Ok(SAMPLE_PR.as_bytes().to_vec());
        }
        Ok(Vec::new())
    }));
    h
}

fn leftovers(h: &Harness) -> Vec<String> {
    sorted_entries(Path::new(&h.tmp()))
        .into_iter()
        .filter(|name| name != "togi-review")
        .collect()
}

#[test]
fn snapshot_too_large_diff_built_locally() {
    let mut h = local_diff_harness(pull_handler("TOO_LARGE", &[HEAD_SHA]), None);
    snapshot(&mut h, &["700"]).expect("snapshot");
    assert_eq!(
        vec!["git remote get-url origin"],
        h.fake.git_joined(),
        "git calls in the caller's checkout"
    );
    let triple_dot = format!("{BASE_SHA}...{HEAD_SHA}");
    let want_args: Vec<Vec<&str>> = vec![
        vec!["init", "--quiet", "--bare", "--template="],
        vec![
            "fetch",
            "--no-tags",
            "--quiet",
            ORIGIN_URL,
            BASE_SHA,
            HEAD_SHA,
        ],
        vec![
            "diff",
            "--no-color",
            "--no-ext-diff",
            "--no-textconv",
            "-M",
            "--src-prefix=a/",
            "--dst-prefix=b/",
            &triple_dot,
        ],
    ];
    let calls = &h.fake.isolated_calls;
    assert_eq!(
        want_args,
        calls
            .iter()
            .map(|(_, args)| args.iter().map(String::as_str).collect::<Vec<_>>())
            .collect::<Vec<_>>()
    );
    for (i, (dir, _)) in calls.iter().enumerate() {
        assert!(
            *dir == calls[0].0 && dir.parent() == Some(h.tmp.path()),
            "isolated git call {i} ran in {}, want one directory directly under {}",
            dir.display(),
            h.tmp()
        );
    }
    assert_eq!(
        "gh pr diff 700 --color=never --allow-escape-sequences",
        h.fake.gh_joined()[1]
    );
    assert!(
        leftovers(&h).is_empty(),
        "the temporary repository was left behind: {:?}",
        leftovers(&h)
    );
    assert_eq!(
        SAMPLE_PR,
        snapshot_file(&h, "pr.diff"),
        "pr.diff is not the locally built diff byte for byte"
    );
    check_golden(
        "snapshot/manifest.golden",
        &snapshot_file(&h, "manifest.json"),
    );
    let m = manifest(&h);
    let want = parse(SAMPLE_PR);
    assert_eq!(
        (
            i64::try_from(want.len()).expect("count"),
            total_lines(&want),
            want.len()
        ),
        (m.pr_files, m.pr_lines, m.files.len())
    );
    for (i, f) in m.files.iter().enumerate() {
        if !f.exclusion.is_empty() {
            assert!(
                !Path::new(&snapshot_dir(&h))
                    .join(hunk_file_name(i + 1))
                    .exists(),
                "excluded file {} has a hunk file",
                f.path
            );
            continue;
        }
        assert_eq!(
            lossy(&want[i].text),
            snapshot_file(&h, &f.hunk_file),
            "{} is not {}'s section",
            f.hunk_file,
            f.path
        );
    }
}

