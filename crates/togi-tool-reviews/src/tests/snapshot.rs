#[test_case("", "", ""; "empty")]
#[test_case("GraphQL: Could not resolve to a PullRequest\n", "", "not a unified diff"; "error text")]
#[test_case("diff --git a/my file b/my file\n--- a/my file\t\n+++ b/my file\t\n@@ -1 +1 @@\n-a\n+b\n", "my file", ""; "tab after a path with spaces")]
#[test_case("diff --git a/run.sh b/run.sh\nold mode 100644\nnew mode 100755\n", "run.sh", ""; "mode change")]
#[test_case("diff --git a/x b/y\nindex 1..2\n", "", "cannot read the path"; "unreadable header")]
#[test_case("diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -1 +1 @@\n-a\n\\ No newline at end of file\n+b\n\\ No newline at end of file\n", "f", ""; "no newline marker")]
fn parse_diff_edges(input: &str, want_path: &str, want_error: &str) {
    let result = parse_diff(input.as_bytes());
    if !want_error.is_empty() {
        let error = result.expect_err("parse_diff accepted");
        assert!(
            error.render().contains(want_error),
            "error = {error}, want one containing {want_error:?}"
        );
        return;
    }
    let files = result.expect("parse");
    if want_path.is_empty() {
        assert!(files.is_empty(), "got {} files, want none", files.len());
    } else {
        assert_eq!(
            vec![want_path],
            files.iter().map(|f| f.path.as_str()).collect::<Vec<_>>()
        );
    }
}

pub(crate) fn one_patch(file: &str, context: &str, added: &str) -> String {
    format!(
        "diff --git a/{file} b/{file}\n--- a/{file}\n+++ b/{file}\n@@ -5,3 +5,3 @@\n {context}\n-old\n+{added}\n tail\n"
    )
}

#[test]
fn same_changes_ignores_context() {
    let patch = |context: &str, added: &str| parse(&one_patch("f", context, added));
    assert!(
        same_changes(&patch("ctx", "new"), &patch("moved context", "new")),
        "a patch whose only difference is its context lines must count as unchanged"
    );
    assert!(
        !same_changes(&patch("ctx", "new"), &patch("ctx", "newer")),
        "an edited added line must count as changed"
    );
}

