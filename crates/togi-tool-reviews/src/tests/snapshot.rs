/// More changed lines never mean fewer reviewers for a fixed file count: every line count 0..=6000 for F
/// 0..=64 crosses every tier boundary (100, 500, 5000) at every file count.
#[test]
fn reviewer_count_nondecreasing() {
    for f in 0..=64 {
        let mut prev = reviewer_count(0, f);
        for l in 1..=6000 {
            let got = reviewer_count(l, f);
            assert!(
                got >= prev,
                "reviewer_count(L={l}, F={f}) = {got}, below {prev} at L={}",
                l - 1
            );
            assert!(
                f == 0 || (1..=f.min(8)).contains(&got),
                "reviewer_count(L={l}, F={f}) = {got}, want 1..min(F, 8)"
            );
            assert!(
                l >= 5000 || got <= 4,
                "reviewer_count(L={l}, F={f}) = {got}, above the 4 cap below 5000 lines"
            );
            prev = got;
        }
    }
}

