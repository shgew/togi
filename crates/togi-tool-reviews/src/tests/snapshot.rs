fn view_call() -> String {
    "gh pr view 700 --json headRefOid,baseRefOid,url".to_owned()
}

fn read_call(name: &str) -> String {
    format!(
        "gh api -H Accept: application/vnd.github.raw+json repos/shgew/togi/contents/{name}?ref={HEAD_SHA}"
    )
}

fn sorted_entries(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .expect("read dir")
        .map(|entry| {
            entry
                .expect("entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    names.sort();
    names
}

#[test]
fn snapshot_first_review() {
    let mut h = Harness::new(Some(pull_handler(SAMPLE_PR, &[HEAD_SHA, HEAD_SHA])), None);
    snapshot(&mut h, &["700"]).expect("snapshot");
    let dir = snapshot_dir(&h);
    assert_eq!(
        SAMPLE_PR,
        snapshot_file(&h, "pr.diff"),
        "pr.diff is not the frozen diff byte for byte"
    );
    check_golden(
        "snapshot/manifest.golden",
        &snapshot_file(&h, "manifest.json"),
    );
    check_golden(
        "snapshot/summary.golden",
        &h.stdout().replace(&dir, "<dir>"),
    );
    let m = manifest(&h);
    let on_disk: Vec<String> = sorted_entries(&Path::new(&dir).join("files"))
        .into_iter()
        .map(|name| format!("files/{name}"))
        .collect();
    let mut named = Vec::new();
    for f in m.included() {
        named.push(f.hunk_file.clone());
        let got = snapshot_file(&h, &f.hunk_file);
        assert!(
            got.starts_with("diff --git ") && SAMPLE_PR.contains(&got),
            "{} is not {}'s section of the diff",
            f.hunk_file,
            f.path
        );
    }
    assert_eq!(
        named, on_disk,
        "hunk files named in the manifest vs written"
    );
    assert!(
        !Path::new(&dir).join("delta.diff").exists(),
        "a first review wrote delta.diff"
    );
    let want_calls = vec![
        view_call(),
        "gh pr diff 700 --color=never --allow-escape-sequences".to_owned(),
        view_call(),
        read_call("cmd/togi/main.go"),
        read_call("docs/two.md"),
        view_call(),
    ];
    assert_eq!(want_calls, h.fake.gh_joined());
}

