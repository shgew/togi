const F: &str = "diff --git a/f b/f\n--- a/f\n+++ b/f\n";
const HUNK_F: &str = "@@ -5,3 +5,2 @@\n ctx\n-F = 1\n tail\n";
const HUNK_G: &str = "@@ -30,3 +29,2 @@\n ctx\n-G = 1\n tail\n";
const LOST_F: &str = "@@ -6 +5,0 @@\n-F = 1\n";
const LOST_G: &str = "@@ -31 +30,0 @@\n-G = 1\n";
const LOST_F1: &str = "@@ -6 +5,0 @@\n-F = 1\n";
const LOST_G1: &str = "@@ -7 +6,0 @@\n-G = 1\n";
const MODE: &str = "diff --git a/f b/f\nold mode 100755\nnew mode 100644\n";
const BINARY: &str =
    "diff --git a/f b/f\nindex 1111111..2222222 100644\nBinary files a/f and b/f differ\n";
const BINARY_CHANGED: &str =
    "diff --git a/f b/f\nindex 2222222..3333333 100644\nBinary files a/f and b/f differ\n";

fn f(rest: &str) -> String {
    format!("{F}{rest}")
}

/// The reversal of a commit that added F and G.
fn two() -> String {
    f(&format!("{HUNK_F}{HUNK_G}"))
}

/// The reversal of a commit that removed a line, "was".
fn removed() -> String {
    f("@@ -5,2 +5,3 @@\n ctx\n+was\n tail\n")
}

/// The reversal of a commit that added the adjacent lines F and G in one hunk.
fn adjacent() -> String {
    f("@@ -5,4 +5,2 @@\n ctx\n-F = 1\n-G = 1\n tail\n")
}

/// The same reversal as `two` with a mode change of the file.
fn mode_text() -> String {
    format!("{MODE}index 1111111..2222222\n--- a/f\n+++ b/f\n{HUNK_F}{HUNK_G}")
}

/// The reversal of a commit that removed the last two lines, x and y, of a file that ended without a newline.
fn no_newline() -> String {
    f("@@ -5 +5,3 @@\n ctx\n+x\n+y\n\\ No newline at end of file\n")
}

/// The reversal of a commit that deleted the file holding a and b.
fn recreated() -> String {
    "diff --git a/f b/f\nnew file mode 100644\nindex 0000000..1111111\n--- /dev/null\n+++ b/f\n@@ -0,0 +1,2 @@\n+a\n+b\n".to_owned()
}

