#[test_case("previous record", "head"; "fetching the previous record, head")]
#[test_case("previous record", "base"; "fetching the previous record, base")]
#[test_case("delta", "head"; "constructing the delta, head")]
#[test_case("delta", "base"; "constructing the delta, base")]
#[test_case("file", "head"; "reading a file at the head, head")]
#[test_case("file", "base"; "reading a file at the head, base")]
fn snapshot_refuses_move_after_remote_work(step: &'static str, side: &'static str) {
    let moved = flag();
    let at = move |args: &[String]| match step {
        "previous record" => args[0] == "api" && args[1].contains("/issues/comments/"),
        "delta" => args[0] == "range-diff",
        _ => args[0] == "api" && args.last().is_some_and(|a| a.contains("/contents/")),
    };
    let trip = |moved: Rc<RefCell<bool>>| -> Hook {
        Box::new(move |args: &[String]| {
            if at(args) {
                *moved.borrow_mut() = true;
            }
        })
    };
    let seen = Rc::clone(&moved);
    let view: View = Box::new(move |_| match (*seen.borrow(), side) {
        (false, _) => (HEAD_SHA.to_owned(), BASE_SHA.to_owned()),
        (true, "head") => (MOVED_SHA.to_owned(), BASE_SHA.to_owned()),
        (true, _) => (HEAD_SHA.to_owned(), MOVED_SHA.to_owned()),
    });
    let mut h = ReReview {
        on_api: Some(trip(Rc::clone(&moved))),
        on_git: Some(trip(Rc::clone(&moved))),
        view: Some(view),
        ..ReReview::new(
            previous_body(3, OLD_BASE_SHA),
            "1:  aaa1111 ! 1:  bbb1111 edit\n",
            &[
                ("aaa1111^ aaa1111", &one_patch("b.go", "ctx", "v1")),
                ("bbb1111^ bbb1111", &one_patch("b.go", "ctx", "v2")),
            ],
        )
    }
    .harness();
    let error = snapshot(&mut h, &["--previous", PREVIOUS_URL, "700"])
        .expect_err("snapshot accepted")
        .render();
    assert!(
        error.contains("moved while the snapshot ran") && error.contains(MOVED_SHA),
        "error = {error}, want a refusal naming the moved {side}"
    );
    assert!(
        *moved.borrow(),
        "the fake never moved the pull request: the step did not run"
    );
    crate::snapshot::tests::assert_no_snapshot(&h);
}

