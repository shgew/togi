fn exclusions(h: &Harness) -> Vec<(String, String)> {
    manifest(h)
        .files
        .into_iter()
        .map(|f| (f.path, f.exclusion))
        .collect()
}

fn rows(rows: &[(&str, &str)]) -> Vec<(String, String)> {
    rows.iter()
        .map(|&(path, exclusion)| (path.to_owned(), exclusion.to_owned()))
        .collect()
}

#[test]
fn snapshot_excludes_generated_files_from_their_contents() {
    let a = format!(
        "/*\n * Copyright\n */\n\n{GENERATED_MARKER}\npackage gen\n{}",
        "// line\n".repeat(30)
    );
    let ren = format!("{GENERATED_MARKER}package gen\nvar a = 2\n");
    let files = contents(&[
        ("gen/a.go", &a),
        ("gen/hand.go", "package gen\nvar a = 1\n"),
        ("gen/ren_new.go", &ren),
    ]);
    let mut h = Harness::new(
        Some(Box::new(pull_fake(GENERATED_DIFF, files, frozen()))),
        None,
    );
    snapshot(&mut h, &["700"]).expect("snapshot");
    assert_eq!(
        rows(&[
            ("gen/a.go", "generated"),
            ("gen/hand.go", ""),
            ("gen/old.go", "generated"),
            ("gen/ren_new.go", "generated")
        ]),
        exclusions(&h)
    );
    let m = manifest(&h);
    assert_eq!(
        (1, 1, 1),
        (m.included_files, m.included_lines, m.reviewers),
        "only the hand-written file counts toward F and L"
    );
    let reads: Vec<String> = h
        .fake
        .gh_joined()
        .into_iter()
        .filter(|c| c.starts_with("gh api "))
        .collect();
    let read = |name: &str| {
        format!(
            "gh api -H Accept: application/vnd.github.raw+json repos/shgew/togi/contents/{name}?ref={HEAD_SHA}"
        )
    };
    assert_eq!(
        vec![
            read("gen/a.go"),
            read("gen/hand.go"),
            read("gen/ren_new.go")
        ],
        reads,
        "a deleted file's section shows its whole content, so it is not read"
    );
}

