#[test]
fn same_changes_metadata() {
    let hunk = "--- a/f\n+++ b/f\n@@ -5,3 +5,3 @@\n ctx\n-old\n+new\n tail\n";
    let exec = parse(&format!(
        "diff --git a/f b/f\nold mode 100644\nnew mode 100755\nindex 1..2\n{hunk}"
    ));
    let plain = parse(&format!("diff --git a/f b/f\nindex 3..4 100644\n{hunk}"));
    assert!(
        !same_changes(&exec, &plain) && !same_changes(&plain, &exec),
        "dropping an executable-bit change counted as context only"
    );
    let moved = parse(&format!(
        "diff --git a/f b/f\nold mode 100644\nnew mode 100755\nindex 5..6\n{}",
        hunk.replacen("ctx", "moved context", 1)
    ));
    assert!(
        same_changes(&exec, &moved),
        "the same mode change with moved context must count as unchanged"
    );
    assert!(
        !same_changes(
            &parse("diff --git a/f b/f\nold mode 100644\nnew mode 100755\n"),
            &parse("diff --git a/f b/f\nold mode 100644\nnew mode 100644\n")
        ),
        "different new modes counted as the same"
    );
    assert!(
        !same_changes(
            &parse("diff --git a/f b/f\nnew file mode 100644\nindex 0000000..e69de29\n"),
            &parse("diff --git a/f b/f\nnew file mode 100755\nindex 0000000..e69de29\n")
        ),
        "an empty file added with a different mode counted as the same"
    );
    let no_newline = parse(
        "diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -1 +1 @@\n-a\n+a\n\\ No newline at end of file\n",
    );
    let newline = parse("diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -1 +1 @@\n-a\n+a\n");
    assert!(
        !same_changes(&no_newline, &newline),
        "a patch that ends the file without a newline counted as the same as one that does not"
    );
    let binary = |old: &str, new: &str, payload: &str| {
        parse(&format!(
            "diff --git a/b.bin b/b.bin\nindex {old}..{new} 100644\nGIT binary patch\n{payload}\n"
        ))
    };
    assert!(
        !same_changes(
            &binary("1111111", "2222222", "literal 1"),
            &binary("1111111", "3333333", "literal 1")
        ),
        "binary files with different resulting objects counted as the same"
    );
    assert!(
        same_changes(
            &binary("1111111", "2222222", "literal 1"),
            &binary("4444444", "2222222", "delta 1")
        ),
        "a binary file with the same resulting object must count as unchanged whatever it was before"
    );
    let no_index = |payload: &str| {
        parse(&format!(
            "diff --git a/b.bin b/b.bin\nGIT binary patch\n{payload}\n"
        ))
    };
    assert!(
        !same_changes(&no_index("literal 1"), &no_index("literal 2"))
            && same_changes(&no_index("literal 1"), &no_index("literal 1")),
        "without an index line binary files must compare by payload"
    );
}

