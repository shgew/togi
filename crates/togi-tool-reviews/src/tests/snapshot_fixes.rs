fn trace_call(target: &str, names: &str) -> String {
    format!("git diff --no-color --no-ext-diff --no-renames -U0 aaa1111 {target} -- {names}")
}

#[test]
fn snapshot_removed_patch_inherited_from_new_base() {
    let mut h = re_review(
        previous_body(3, OLD_BASE_SHA),
        "1:  aaa1111 < -:  ------- moved down into the base\n",
        &[
            ("aaa1111 aaa1111^", &one_patch("d.go", "ctx", "inherited")),
            // The new head still has everything the commit did to d.go: the base carries it now.
            ("aaa1111 -- d.go", ""),
        ],
    );
    snapshot(&mut h, &["--previous", PREVIOUS_URL, "700"]).expect("snapshot");
    let m = manifest(&h);
    assert_eq!(
        vec![patch_status(
            "aaa1111",
            "",
            "moved down into the base",
            "removed",
            false
        )],
        m.patches
    );
    assert!(
        m.files.is_empty() && m.included_files == 0 && m.reviewers == 0 && !m.carry_forward,
        "want a lower-layer change not assigned to this layer as a removal: {m:?}"
    );
    assert_eq!("", snapshot_file(&h, "delta.diff"));
    let calls = h.fake.git_joined();
    for target in [BASE_SHA, HEAD_SHA] {
        let want = trace_call(target, ":(literal)d.go");
        assert!(
            calls.contains(&want),
            "git calls {calls:?} lack the effect trace {want:?}"
        );
    }
}

