#[test_case(&adjacent(), &f(LOST_F1), &f(LOST_F1), &f("@@ -5,4 +5,3 @@\n ctx\n-F = 1\n G = 1\n tail\n"); "adjacent additions, only F lost")]
#[test_case(&adjacent(), &f("@@ -6,2 +5,0 @@\n-F = 1\n-G = 1\n"), &f("@@ -6,2 +5,0 @@\n-F = 1\n-G = 1\n"), &adjacent(); "adjacent additions, both lost")]
#[test_case(&adjacent(), &f(LOST_G1), "", ""; "adjacent additions, G lost in the base only")]
